export function translate(
  language: LanguageCode,
  key: TranslationKey,
): string {
  return translations[language][key] ??
    translations.en[key] ??
    key;
}

export function resolveTranslatedField(
  language: LanguageCode,
  englishValue: string | null | undefined,
  translatedValue: string | null | undefined,
  status: string | null | undefined,
  requiresReview = false,
  reviewedAt: string | null = null,
): { value: string; usedFallback: boolean } {
  const approved =
    (status === "published" ||
      (!requiresReview && status === "reviewed")) &&
    (!requiresReview || Boolean(reviewedAt));

  if (
    language !== "en" &&
    translatedValue?.trim() &&
    approved
  ) {
    return {
      value: translatedValue,
      usedFallback: false,
    };
  }

  return {
    value: englishValue?.trim() || "",
    usedFallback: language !== "en",
  };
}